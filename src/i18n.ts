export type Message = keyof typeof zhCN;
export type Translate = (key: Message, values?: Record<string, string | number>) => string;
export function translator(locale: string | undefined): Translate {
  return (key, values = {}) => (locale === 'zh-CN' ? zhCN[key] : key)
    .replace(/\{(\w+)\}/g, (token, name: string) => Object.hasOwn(values, name) ? String(values[name]) : token);
}
